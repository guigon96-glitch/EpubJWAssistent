const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  openEpub: () => ipcRenderer.invoke('open-epub'),
  saveEpub: (opts) => ipcRenderer.invoke('save-epub', opts),
  confirm: (message, buttons) => ipcRenderer.invoke('confirm', { message, buttons }),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  openRefFile: () => ipcRenderer.invoke('open-ref-file'),
  readClipboard: () => ipcRenderer.invoke('read-clipboard'),
  openRefWindow: (content) => ipcRenderer.send('open-ref-window', content),
  openWol: () => ipcRenderer.send('open-wol'),
  onRefContent: (fn) => ipcRenderer.on('ref-content', (_e, c) => fn(c)),
  appInfo: () => ipcRenderer.invoke('app-info'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  update: {
    check: () => ipcRenderer.invoke('upd-check'),
    download: () => ipcRenderer.invoke('upd-download'),
    install: () => ipcRenderer.invoke('upd-install'),
    onProgress: (fn) => ipcRenderer.on('upd-progress', (_e, p) => fn(p)),
  },
  lib: {
    info: () => ipcRenderer.invoke('lib-info'),
    openFolder: () => ipcRenderer.invoke('lib-open-folder'),
    list: (source) => ipcRenderer.invoke('lib-list', { source }),
    createCategory: (source, name) => ipcRenderer.invoke('lib-cat-create', { source, name }),
    renameCategory: (source, id, name) => ipcRenderer.invoke('lib-cat-rename', { source, id, name }),
    deleteCategory: (source, id) => ipcRenderer.invoke('lib-cat-delete', { source, id }),
    move: (source, id, to) => ipcRenderer.invoke('lib-move', { source, id, to }),
    trash: (source, id) => ipcRenderer.invoke('lib-trash', { source, id }),
    read: (source, id) => ipcRenderer.invoke('lib-read', { source, id }),
    save: (o) => ipcRenderer.invoke('lib-save', o),
  },
  google: {
    status: () => ipcRenderer.invoke('g-status'),
    login: () => ipcRenderer.invoke('g-login'),
    cancel: () => ipcRenderer.invoke('g-cancel'),
    logout: () => ipcRenderer.invoke('g-logout'),
    importConfig: () => ipcRenderer.invoke('g-import-config'),
  },
  bibleFetch: (url) => ipcRenderer.invoke('bible-fetch', url),
  setDirty:(v) => ipcRenderer.send('set-dirty', v),
  setTitle: (t) => ipcRenderer.send('set-title', t),
  closeNow: () => ipcRenderer.send('close-now'),
  onSaveAndClose: (fn) => ipcRenderer.on('save-and-close', fn),
  onCtxQuery: (fn) => ipcRenderer.on('ctx-query', () => ipcRenderer.send('ctx-info', fn())),
  onCtxAction: (fn) => ipcRenderer.on('ctx-action', (_e, a) => fn(a)),
});
